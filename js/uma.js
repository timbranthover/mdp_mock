    var WASH = 30 * DAY;
    /* security moves approved on one model in the last 30 days: [{ticker, dir, t, from, to}] */
    function movesOf(m, now) {
      var out = [];
      m.events.forEach(function (e) {
        if (e.event !== 'Model Approved' || !e.changes) return;
        var t = wall(e.ts);
        if (now - t > WASH) return;
        e.changes.forEach(function (c) { if (c.ticker !== CASH && Math.abs(c.to - c.from) > EPS) out.push({ ticker: c.ticker, dir: c.to > c.from ? 1 : -1, t: t, from: c.from, to: c.to }); });
      });
      return out;
    }
    /* A conflict: one sleeve of the portfolio reduced a security and a different sleeve added it within 30 days.
       `pending` = {access, changes} adds an unsubmitted change as if approved now. */
    function conflicts(p, pending) {
      var now = nowWall(), by = {}, out = [];
      p.sleeves.forEach(function (s) {
        var m = model(s.access); if (!m) return;
        var mv = movesOf(m, now);
        if (pending && pending.access === s.access) pending.changes.forEach(function (c) { if (c.ticker !== CASH && Math.abs(c.to - c.from) > EPS) mv.push({ ticker: c.ticker, dir: c.to > c.from ? 1 : -1, t: now, from: c.from, to: c.to, pending: true }); });
        mv.forEach(function (x) { x.access = s.access; x.alloc = s.alloc; (by[x.ticker] = by[x.ticker] || []).push(x); });
      });
      Object.keys(by).forEach(function (t) {
        var sells = by[t].filter(function (x) { return x.dir < 0; }), buys = by[t].filter(function (x) { return x.dir > 0; }), best = null;
        sells.forEach(function (s) { buys.forEach(function (b) {
          if (s.access === b.access || Math.abs(s.t - b.t) > WASH) return;
          if (pending && !s.pending && !b.pending) return;
          if (!best || Math.max(s.t, b.t) > Math.max(best.sell.t, best.buy.t)) best = { ticker: t, sell: s, buy: b, days: Math.round(Math.abs(s.t - b.t) / DAY) };
        }); });
        if (best) out.push(best);
      });
      return out;
    }
